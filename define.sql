
    create table messaggi_sistema (
        msg varchar(100) not null,
        code varchar(255) not null,
        primary key (code)
    );

    create table utente (
        data_creazione date,
        email_validation BOOLEAN DEFAULT false not null,
        id integer generated by default as identity,
        sesso boolean,
        role varchar(30) not null check ((role in ('ADMIN','USER'))),
        user_name varchar(100) not null unique,
        cap varchar(255),
        cognome varchar(255),
        comune varchar(255),
        email varchar(255),
        nome varchar(255),
        pwd varchar(255) not null,
        telefono varchar(255),
        via varchar(255),
        primary key (id)
    );
